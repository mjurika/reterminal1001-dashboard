/**
 * Generates firmware headers from the web side, so the device draws with the same geometry and typeface:
 *   firmware/include/layout.h  – hole rectangles from layout.json
 *   firmware/include/fonts.h   – Adafruit-GFX fonts rasterized from Barlow Condensed (same as the template)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { ROOT, loadLayout } from './common.ts';
import { startServer } from './server.ts';

interface FontSpec { name: string; weight: number; size: number; first: number; last: number }

// Keep in sync with the hole CSS in preview/index.html (.hole.clock / .indoor / .battery).
const FONTS: FontSpec[] = [
  { name: 'FontClock', weight: 700, size: 144, first: 0x2d, last: 0x3a }, // "-./0123456789:"
  { name: 'FontMedium', weight: 700, size: 56, first: 0x20, last: 0x7e },
  { name: 'FontSmall', weight: 600, size: 22, first: 0x20, last: 0x7e },
];

interface Glyph { w: number; h: number; xAdvance: number; xOffset: number; yOffset: number; bits: number[] }

async function rasterize(spec: FontSpec, page: import('playwright').Page): Promise<Glyph[]> {
  return page.evaluate(async ({ weight, size, first, last }) => {
    const font = `${weight} ${size}px "Barlow Condensed"`;
    await document.fonts.load(font);
    const S = size * 2;
    const canvas = document.createElement('canvas');
    canvas.width = S;
    canvas.height = S;
    const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
    const ox = Math.round(size / 2);
    const base = Math.round(size * 1.4);
    const glyphs = [];
    for (let c = first; c <= last; c++) {
      const ch = String.fromCharCode(c);
      ctx.clearRect(0, 0, S, S);
      ctx.font = font;
      ctx.fillStyle = '#000';
      ctx.textBaseline = 'alphabetic';
      ctx.fillText(ch, ox, base);
      const { data } = ctx.getImageData(0, 0, S, S);
      let x0 = S, y0 = S, x1 = -1, y1 = -1;
      for (let y = 0; y < S; y++) {
        for (let x = 0; x < S; x++) {
          if (data[(y * S + x) * 4 + 3] >= 128) {
            if (x < x0) x0 = x;
            if (x > x1) x1 = x;
            if (y < y0) y0 = y;
            if (y > y1) y1 = y;
          }
        }
      }
      const xAdvance = Math.round(ctx.measureText(ch).width);
      if (x1 < 0) {
        glyphs.push({ w: 0, h: 0, xAdvance, xOffset: 0, yOffset: 0, bits: [] });
        continue;
      }
      const bits = [];
      for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) bits.push(data[(y * S + x) * 4 + 3] >= 128 ? 1 : 0);
      glyphs.push({ w: x1 - x0 + 1, h: y1 - y0 + 1, xAdvance, xOffset: x0 - ox, yOffset: y0 - base, bits });
    }
    return glyphs;
  }, spec);
}

/** GFXfont format: per glyph, bits packed continuously MSB-first, padded to a byte at glyph end. */
function fontHeader(spec: FontSpec, glyphs: Glyph[]): string {
  const bytes: number[] = [];
  const entries: string[] = [];
  glyphs.forEach((g, i) => {
    const offset = bytes.length;
    let acc = 0, n = 0;
    for (const b of g.bits) {
      acc = (acc << 1) | b;
      if (++n === 8) { bytes.push(acc); acc = 0; n = 0; }
    }
    if (n) bytes.push(acc << (8 - n));
    if (g.w > 255 || g.h > 255) throw new Error(`${spec.name}: glyph too large`);
    const ch = String.fromCharCode(spec.first + i);
    entries.push(`  { ${offset}, ${g.w}, ${g.h}, ${g.xAdvance}, ${g.xOffset}, ${g.yOffset} }, // '${ch === '\\' ? 'backslash' : ch}'`);
  });
  const hex = bytes.map((b) => `0x${b.toString(16).padStart(2, '0')}`);
  const rows = [];
  for (let i = 0; i < hex.length; i += 16) rows.push(`  ${hex.slice(i, i + 16).join(', ')}`);
  return `// ${spec.name}: Barlow Condensed ${spec.weight}, ${spec.size}px, chars 0x${spec.first.toString(16)}-0x${spec.last.toString(16)}
const uint8_t ${spec.name}Bitmaps[] PROGMEM = {
${rows.join(',\n')}
};

const GFXglyph ${spec.name}Glyphs[] PROGMEM = {
${entries.join('\n')}
};

const GFXfont ${spec.name} PROGMEM = { (uint8_t *)${spec.name}Bitmaps, (GFXglyph *)${spec.name}Glyphs, 0x${spec.first.toString(16)}, 0x${spec.last.toString(16)}, ${Math.round(spec.size * 1.2)} };
`;
}

const layout = loadLayout();
const holes = Object.entries(layout.holes)
  .map(([name, r]) => `constexpr Rect HOLE_${name.toUpperCase()} = { ${r.x}, ${r.y}, ${r.w}, ${r.h} };`)
  .join('\n');
writeFileSync(
  join(ROOT, 'firmware', 'include', 'layout.h'),
  `#pragma once
// Generated by "npm run gen:firmware" from layout.json – do not edit.
#include <stdint.h>

struct Rect { int16_t x, y, w, h; };

constexpr int16_t SCREEN_W = ${layout.width};
constexpr int16_t SCREEN_H = ${layout.height};
${holes}
`,
);

const { server, url } = await startServer();
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.goto(`${url}/template/dashboard.html`);
  let out = `#pragma once
// Generated by "npm run gen:firmware" – do not edit.
// Barlow Condensed © The Barlow Project Authors, SIL Open Font License 1.1.
#include <Adafruit_GFX.h>

`;
  for (const spec of FONTS) {
    const glyphs = await rasterize(spec, page);
    out += fontHeader(spec, glyphs) + '\n';
    console.log(`${spec.name}: ${glyphs.length} glyphs`);
  }
  writeFileSync(join(ROOT, 'firmware', 'include', 'fonts.h'), out);
  console.log('firmware/include/layout.h + fonts.h written');
} finally {
  await browser.close();
  server.close();
}
